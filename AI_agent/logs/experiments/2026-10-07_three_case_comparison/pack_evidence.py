"""Pack the six comparison run folders for the evidence branch (no model calls).

Usage: python pack_evidence.py <out_dir>
Each run folder under AI_agent/archive/local_backup/cmp3 (plus its launch/stdout/stderr/exit files from the run
worktree when present) becomes <out_dir>/cmp3_<run>.tar.xz. Writes <out_dir>/evidence_manifest_full.json (every
file's SHA-256) and evidence_manifest.json next to this script (one row per archive). Post-hoc folders are excluded:
they are regenerated by posthoc.py.
"""
import hashlib
import json
from pathlib import Path
import sys
import tarfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
RUNS = ROOT / "AI_agent/archive/local_backup/cmp3"
LOGS = Path(r"C:/Users/Horton/Desktop/EnergyPlus-Agent-worktrees/runs-cmp3/AI_agent/archive/local_backup/cmp3")
ORDER = ["sm24_single", "sm24_role", "sm21_role", "sm21_single", "sm25_single", "sm25_role"]
BRANCH = "evidence/three-case-comparison-2026-10-07"
SKIP = {"posthoc_overlays", "posthoc_display"}


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main(out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    full, slim = {}, []
    for name in ORDER:
        run = RUNS / name
        files = sorted(p for p in run.rglob("*") if p.is_file() and SKIP.isdisjoint(p.relative_to(run).parts))
        extras = sorted(p for p in LOGS.glob(f"{name}.*") if p.is_file())
        archive = out_dir / f"cmp3_{name}.tar.xz"
        with tarfile.open(archive, "w:xz", preset=6) as tar:
            for path in files:
                tar.add(path, arcname=f"{name}/{path.relative_to(run).as_posix()}", recursive=False)
            for path in extras:
                tar.add(path, arcname=f"{name}/_launch/{path.name}", recursive=False)
        full[archive.name] = {f"{name}/{p.relative_to(run).as_posix()}": sha256(p) for p in files}
        full[archive.name].update({f"{name}/_launch/{p.name}": sha256(p) for p in extras})
        slim.append({"archive": archive.name, "archive_sha256": sha256(archive), "archive_bytes": archive.stat().st_size,
                     "files": len(files) + len(extras), "source": f"AI_agent/archive/local_backup/cmp3/{name}"})
        print(name, archive.stat().st_size, len(files) + len(extras), flush=True)
    (out_dir / "evidence_manifest_full.json").write_text(
        json.dumps({"schema_version": "evidence-manifest-full-v1", "branch": BRANCH, "archives": full},
                   ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    (HERE / "evidence_manifest.json").write_text(json.dumps(
        {"schema_version": "evidence-manifest-slim-v1", "branch": BRANCH,
         "full_manifest": "evidence_manifest_full.json (on the evidence branch)", "archives": slim},
        ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
